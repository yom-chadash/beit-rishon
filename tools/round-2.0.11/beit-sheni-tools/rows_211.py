def set_model(it, old_start, new_text):
    """replace the paragraph of `it`['info'] that starts with old_start (to the line's end) by new_text; idempotent"""
    info = it['info']
    if new_text in info:
        return
    k = info.find(old_start)
    assert k >= 0, (it.get('t'), old_start)
    e = info.find('\n', k)
    it['info'] = info[:k] + new_text + (info[e:] if e >= 0 else '')

