def clean_text(t):
    for pat, rep in RULES: t = re.sub(pat, rep, t)
    return t

def _texts(C):
    for k in list(C['INFO']): yield ('INFO/' + k, C['INFO'], k)
    for g in C['PLACES']:
        for it in g[1]:
            if isinstance(it.get('info'), str): yield ('P/' + it['t'], it, 'info')
    for r in C['SHITOT']:
        for o in r['opts']:
            if isinstance(o.get('info'), str): yield ('S/' + r['t'] + '/' + o['t'], o, 'info')
    for it in C['CORRECTIONS']:
        if isinstance(it.get('info'), str): yield ('C/' + it['t'], it, 'info')
    for k, v in C['LABEL_MAP'].items():
        if isinstance(v, dict) and isinstance(v.get('info'), str): yield ('L/' + k, v, 'info')

def clean_content(C, strict=True):
    seen = [0] * len(EXACT)
    for path, holder, key in _texts(C):
        t = holder[key]
        if not isinstance(t, str): continue
        for i, (old, new, cnt) in enumerate(EXACT):
            n = t.count(old)
            if n: seen[i] += n; t = t.replace(old, new)
        holder[key] = clean_text(t)
    bad = [(EXACT[i][0][:70], seen[i], EXACT[i][2]) for i in range(len(EXACT)) if (seen[i] != EXACT[i][2] if EXACT[i][2] is not None else seen[i] < 1)]
    if bad and strict: raise AssertionError('textpass_211r: EXACT not found as counted: %r' % bad[:6])
    return C

LEFT = [('version', r'מ־\d|גרסה \d|עד אז|ב־\d\.\d|עד \d\.\d'), ('kria', r'קריא(?:ה|ות|ת (?!שמע|הגבר|התורה))'), ('shura', r'בשור(?:ה|ת) ״|השורה ״|בשורה שב|שורת ״'),
        ('table', r'טבלת(?! השיש)|בטבלה|קטגורי'), ('words', r'כהן שלם|בדגם|לא מצאתי|לא מאומת|בעקבות ההערות|לצייר ולציין|אינו בספרייה|תוסף בית ראשון|בשני התוספים')]
def leftovers(C, w=34):
    out = []
    for path, holder, key in _texts(C):
        t = holder[key]
        for name, pat in LEFT:
            for m in re.finditer(pat, t):
                out.append((name, path[:30], t[max(0, m.start() - w):m.end() + w].replace('\n', '⏎')))
    return out

