def book(bid):
    f = glob.glob('%s/%d - *.txt' % (T, bid))[0]
    out = {}
    for line in open(f, encoding='utf-8'):
        p = line.rstrip('\n').split('\t')
        if len(p) >= 3 and p[1]:
            out[p[1]] = (int(p[0]), TAG.sub('', p[2]))
    return out

