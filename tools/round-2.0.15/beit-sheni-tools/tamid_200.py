def unpoint(s):
    u, idx = [], []
    for i, ch in enumerate(s):
        if NIK.match(ch):
            continue
        u.append(' ' if ch == '־' else ch)
        idx.append(i)
    return ''.join(u), idx

def cut(s, start=None, end=None):
    s = re.sub(r'^\([א-ת]+\)\s*', '', s).strip()
    u, idx = unpoint(s)
    a = u.find(start) if start else 0
    if a < 0:
        raise SystemExit('start not found: %r in %r' % (start, u[:120]))
    if end:
        b = u.find(end, a)
        if b < 0:
            raise SystemExit('end not found: %r after %r' % (end, start))
        b += len(end)
    else:
        b = len(u)
    i0, i1 = idx[a], (idx[b] if b < len(idx) else len(s))
    return s[i0:i1].strip()

